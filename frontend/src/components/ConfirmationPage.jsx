
import React, { useEffect, useState } from "react";
import { QRCodeSVG } from "qrcode.react";
import { useNavigate } from "react-router-dom";
import jsPDF from "jspdf";
import { getQrByBooking } from "../api/api";

import "./ConfirmationPage.css";

const HOURLY_RATE = 50;

function money(value) {
  return Number(value ?? 0).toFixed(2);
}

function displayDate(value) {
  if (!value) return "Not set";

  const date = new Date(value);

  return Number.isNaN(date.getTime())
    ? String(value)
    : date.toLocaleString();
}

function getBookingAmount(booking) {
  if (booking.amount !== null && booking.amount !== undefined) {
    return Number(booking.amount);
  }

  return Number(booking.durationHours || 1) * HOURLY_RATE;
}

// Generate a PDF receipt containing the saved booking details.
function buildReceiptPdf(booking) {
  const doc = new jsPDF({ unit: "pt", format: "a5" });
  const pageWidth = doc.internal.pageSize.getWidth();
  const centerX = pageWidth / 2;

  doc.setFillColor(28, 110, 74);
  doc.rect(0, 0, pageWidth, 70, "F");

  doc.setTextColor(255, 255, 255);
  doc.setFontSize(18);
  doc.text("Smart Parking - Payment Receipt", centerX, 34, {
    align: "center",
  });

  doc.setFontSize(10);
  doc.text("Green Meadows Apartments", centerX, 52, {
    align: "center",
  });

  doc.setTextColor(31, 42, 36);

  let y = 100;

  const row = (label, value) => {
    // Start a new page if the receipt becomes too long.
    if (y > doc.internal.pageSize.getHeight() - 55) {
      doc.addPage();
      y = 45;
    }

    doc.setFontSize(10);
    doc.setTextColor(107, 122, 114);
    doc.text(label, 40, y);

    doc.setFontSize(12);
    doc.setTextColor(31, 42, 36);
    doc.text(String(value ?? "-"), 40, y + 16);

    y += 34;
  };

  row("Booking ID", booking.bookingId);
  row("Slot", booking.slotId);
  row("Name", booking.name);
  row("Phone", booking.phone);
  row("Status", String(booking.status || "CONFIRMED").toUpperCase());
  row("Parking duration", `${booking.durationHours || 1} hour(s)`);
  row("Hourly rate", `Rs. ${HOURLY_RATE}/hour`);
  row("Total paid", `Rs. ${money(getBookingAmount(booking))}`);
  row("Scheduled start", displayDate(booking.scheduledStartAt));
  row("Scheduled end", displayDate(booking.scheduledEndAt));
  row("Receipt issued", new Date().toLocaleString());

  if (y > doc.internal.pageSize.getHeight() - 45) {
    doc.addPage();
    y = 45;
  }

  doc.setDrawColor(225, 231, 227);
  doc.line(40, y, pageWidth - 40, y);

  doc.setFontSize(8);
  doc.setTextColor(107, 122, 114);
  doc.text(
    "Payment receipt. Refer to your payment provider for transaction details.",
    centerX,
    y + 16,
    {
      align: "center",
      maxWidth: pageWidth - 80,
    }
  );

  doc.save(`receipt-${booking.bookingId}.pdf`);
}

export default function ConfirmationPage({ booking }) {
  const navigate = useNavigate();

  const [currentBooking, setCurrentBooking] = useState(booking || null);
  const [qr, setQr] = useState(null);
  const [qrLoading, setQrLoading] = useState(true);
  const [qrError, setQrError] = useState("");

  // Keep the current booking synchronized with App state.
  useEffect(() => {
    setCurrentBooking(booking || null);
  }, [booking]);

  // Load the QR generated by the backend.
  useEffect(() => {
    if (!currentBooking?.bookingId) {
      setQr(null);
      setQrLoading(false);
      setQrError("");
      return;
    }

    let cancelled = false;

    setQrLoading(true);
    setQrError("");
    setQr(null);

    getQrByBooking(currentBooking.bookingId)
      .then((data) => {
        if (!cancelled) {
          setQr(data);
        }
      })
      .catch((error) => {
        console.error("QR loading error:", error);

        if (!cancelled) {
          setQrError(
            "Unable to load your parking QR. Please refresh the page."
          );
        }
      })
      .finally(() => {
        if (!cancelled) {
          setQrLoading(false);
        }
      });

    return () => {
      cancelled = true;
    };
  }, [currentBooking?.bookingId]);

  if (!currentBooking) {
    return (
      <div className="page">
        <div className="container">
          <div className="card">
            <p>No booking found.</p>

            <button
              type="button"
              className="btn btn-primary"
              onClick={() => navigate("/")}
            >
              Back to Home
            </button>
          </div>
        </div>
      </div>
    );
  }

  const durationHours = Number(currentBooking.durationHours || 1);
  const totalAmount = getBookingAmount(currentBooking);

  return (
    <div className="page">
      <div className="container">
        <div className="card confirmation-card">
          <div className="progress">
            <span className="progress-step active" />
            <span className="progress-step active" />
            <span className="progress-step active" />
            <span className="progress-step active" />
          </div>

          <div className="success-badge">✅</div>

          <h1 className="title">Booking Confirmed!</h1>

          <p className="subtitle">
            Show this QR code at the entrance.
          </p>

          {/* Backend-generated parking QR */}
          <div className="qr-wrapper">
            {qrLoading && <p>Loading parking QR...</p>}

            {!qrLoading && qrError && (
              <>
                <p role="alert">{qrError}</p>

                <button
                  type="button"
                  className="btn btn-secondary"
                  onClick={() => window.location.reload()}
                >
                  Refresh
                </button>
              </>
            )}

            {!qrLoading && !qrError && qr && (
              <>
                <QRCodeSVG
                  value={qr.token}
                  size={180}
                  level="H"
                />

                <p
                  style={{
                    marginTop: 10,
                    fontSize: 13,
                    color: "#6b7a72",
                  }}
                >
                  Show this QR code at the parking entrance.
                </p>

                <p
                  style={{
                    marginTop: 4,
                    fontSize: 12,
                    color: "#8a968f",
                  }}
                >
                  QR Status: {qr.status}
                </p>
              </>
            )}

            {!qrLoading && !qrError && !qr && (
              <>
                <p>Parking QR is not available.</p>

                <button
                  type="button"
                  className="btn btn-secondary"
                  onClick={() => window.location.reload()}
                >
                  Refresh
                </button>
              </>
            )}
          </div>

          {/* Current booking details */}
          <div className="booking-summary">
            <div>
              <span>Booking ID</span>
              <strong>{currentBooking.bookingId}</strong>
            </div>

            <div>
              <span>Slot</span>
              <strong>{currentBooking.slotId}</strong>
            </div>

            <div>
              <span>Name</span>
              <strong>{currentBooking.name}</strong>
            </div>

            <div>
              <span>Phone</span>
              <strong>{currentBooking.phone}</strong>
            </div>

            <div>
              <span>Status</span>
              <strong className="status-confirmed">
                {currentBooking.status}
              </strong>
            </div>

            <div>
              <span>Parking duration</span>
              <strong>{durationHours} hour(s)</strong>
            </div>

            <div>
              <span>Hourly rate</span>
              <strong>₹{HOURLY_RATE}/hour</strong>
            </div>

            <div>
              <span>Total paid</span>
              <strong>₹{money(totalAmount)}</strong>
            </div>

            <div>
              <span>Scheduled start time</span>
              <strong>
                {displayDate(currentBooking.scheduledStartAt)}
              </strong>
            </div>

            <div>
              <span>Scheduled end time</span>
              <strong>
                {displayDate(currentBooking.scheduledEndAt)}
              </strong>
            </div>
          </div>

          {/* Download receipt */}
          <button
            type="button"
            className="btn btn-primary btn-block"
            style={{ marginTop: 16 }}
            onClick={() => buildReceiptPdf(currentBooking)}
          >
            Download receipt (PDF)
          </button>

          <button
            type="button"
            className="btn btn-secondary btn-block"
            style={{ marginTop: 10 }}
            onClick={() => navigate("/")}
          >
            Back to Home
          </button>
        </div>
      </div>
    </div>
  );
}
